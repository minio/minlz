// Command simdneon writes the batched NEON operation loops of SIMD blocks.
//
// The loops expand the literal lengths and offset symbols of 8 operations at a time into
// one byte per operation, 0 where an operation has none, so each operation takes its byte
// with UBFX instead of a conditional load and pointer advance. The operations of a batch are
// unrolled, and each needs its own labels for its out-of-line paths, which assembler macros
// can't make, so the loops are written as text here.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
)

//go:generate go run . -out ../../decode-simd-batch_arm64.s
//go:generate go tool asmfmt -w ../../decode-simd-batch_arm64.s

var out = flag.String("out", "decode-simd-batch_arm64.s", "output file")

type gen struct{ bytes.Buffer }

// i writes an instruction.
func (g *gen) i(format string, a ...any) { fmt.Fprintf(g, "\t"+format+"\n", a...) }

// l writes a label.
func (g *gen) l(name string) { fmt.Fprintf(g, "\n%s:\n", name) }

// c writes a comment line.
func (g *gen) c(format string, a ...any) { fmt.Fprintf(g, "\t// "+format+"\n", a...) }

const header = `// Code generated by command: go run main.go -out ../../decode-simd-batch_arm64.s. DO NOT EDIT.

//go:build arm64 && !appengine && !noasm && gc && !purego

#include "textflag.h"

// The batched operation loops of SIMD blocks. See decode-simd_arm64.s for the copies, and
// _generate/simdneon for the expansion of the literal lengths and offset symbols.

#define DST R0
#define LITP R1
#define TOKP R2
#define LLP R3
#define OFFP R4
#define RAW R5
#define ESCP R6
#define LEFT R7
#define ST R8
#define DP R9
#define LAST R10
#define POS R11
#define TOK R12
#define LEN R13
#define C32 R17
#define OFFTAB R19
#define PERMTAB R20
#define TW R21
#define LW R22
#define SW R23
#define LWN R24
#define SWN R25
#define ONES R26
`

// loop is one of the four operation loops.
type loop struct {
	name        string
	delta, flat bool
}

func main() {
	flag.Parse()
	var g gen
	g.WriteString(header)
	for _, lp := range []loop{
		{"simdExecBatchNEON", false, false},
		{"simdExecBatchDeltaNEON", true, false},
		{"simdExecBatchFlatNEON", false, true},
		{"simdExecBatchFlatDeltaNEON", true, true},
	} {
		g.function(lp)
	}
	if err := os.WriteFile(*out, g.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func (g *gen) function(lp loop) {
	args, size := "n int, st *[4]int", 72
	if lp.flat {
		args, size = "n, pos int, st *[4]int", 80
	}
	fmt.Fprintf(g, "\n// func %s(dst *byte, lits *byte, tok *byte, ll *byte, offc *byte, raw *byte, esc *byte, %s)\n", lp.name, args)
	fmt.Fprintf(g, "TEXT ·%s(SB), NOSPLIT, $0-%d\n", lp.name, size)
	g.i("MOVD dst+0(FP), DST")
	g.i("MOVD lits+8(FP), LITP")
	g.i("MOVD tok+16(FP), TOKP")
	g.i("MOVD ll+24(FP), LLP")
	g.i("MOVD offc+32(FP), OFFP")
	g.i("MOVD raw+40(FP), RAW")
	g.i("MOVD esc+48(FP), ESCP")
	g.i("MOVD n+56(FP), LEFT")
	g.i("MOVD ZR, POS")
	if lp.flat {
		g.i("MOVD st+72(FP), ST")
		g.i("MOVD pos+64(FP), POS")
	} else {
		g.i("MOVD st+64(FP), ST")
	}
	g.i("MOVD (ST), DP")
	g.i("ADD DST, DP")
	g.i("MOVD 8(ST), R14")
	g.i("ADD R14, LITP")
	g.i("MOVD 16(ST), LAST")
	g.i("MOVD $·simdOffTabNEON(SB), OFFTAB")
	g.i("MOVD $·simdPermTabNEON(SB), PERMTAB")
	g.i("MOVD $0x0101010101010101, ONES")
	if lp.flat && lp.delta {
		g.i("MOVD $32, C32")
	}
	g.i("CBZ LEFT, done")
	g.expand()

	// Each batch takes the words expanded before it, and expands the next batch while it runs,
	// if there is one. The words of a partial last batch hold values past n, which are not used.
	g.c("LEFT is the number of operations left, from TOKP on.")
	g.i("PCALIGN $64")
	g.l("loop")
	g.i("CMP $8, LEFT")
	g.i("BLO tail")
	g.i("MOVD.P 8(TOKP), TW")
	g.i("MOVD LWN, LW")
	g.i("MOVD SWN, SW")
	g.i("SUBS $8, LEFT")
	g.i("BEQ batch")
	g.expand()
	g.l("batch")
	for k := range 8 {
		g.op(lp, fmt.Sprint(k), k)
	}
	g.i("B loop")

	g.l("tail")
	g.i("CBZ LEFT, done")
	g.i("MOVD (TOKP), TW")
	g.i("MOVD LWN, LW")
	g.i("MOVD SWN, SW")
	g.l("tailloop")
	g.op(lp, "t", -1)
	g.i("SUBS $1, LEFT")
	g.i("BNE tailloop")

	g.l("done")
	g.i("SUB DST, DP")
	g.i("MOVD DP, (ST)")
	g.i("MOVD lits+8(FP), R14")
	g.i("SUB R14, LITP")
	g.i("MOVD LITP, 8(ST)")
	g.i("MOVD LAST, 16(ST)")
	g.i("RET")

	for k := range 8 {
		g.slow(lp, fmt.Sprint(k))
	}
	g.slow(lp, "t")
}

// expand expands the literal lengths and offset symbols of the 8 operations at TOKP into LWN and SWN,
// and advances LLP and OFFP past their values.
// F has byte i set for a value, P = F * ONES counts them in bytes 0 to i, and P - F gives the index
// of each value. Bytes without a value get index 0x80, for which TBL gives 0.
func (g *gen) expand() {
	g.i("MOVD (TOKP), R14")
	for _, s := range []struct{ p, w, idx, tab string }{{"LLP", "LWN", "V16", "V17"}, {"OFFP", "SWN", "V18", "V19"}} {
		if s.p == "LLP" {
			g.i("LSR $1, R14, R15")
			g.i("AND ONES, R15")
		} else {
			// A repeat has no offset symbol, and gets symbol 0.
			g.i("BIC R14, ONES, R15")
		}
		g.i("MUL ONES, R15, R16")
		g.i("SUB R15, R16, R13")
		g.i("EOR ONES, R15")
		g.i("ORR R15<<7, R13")
		g.i("FMOVD R13, F%s", s.idx[1:])
		g.i("FMOVD (%s), F%s", s.p, s.tab[1:])
		g.i("VTBL %s.B8, [%s.B16], %s.B8", s.idx, s.tab, s.idx)
		g.i("FMOVD F%s, %s", s.idx[1:], s.w)
		g.i("ADD R16>>56, %s", s.p)
	}
}

// byteOf sets dst to the value of operation k of the batch in word w.
// The tail loop takes byte 0 and shifts the word down.
func (g *gen) byteOf(w string, k int, dst string) {
	if k < 0 {
		g.i("AND $0xff, %s, %s", w, dst)
		g.i("LSR $8, %s", w)
		return
	}
	g.i("UBFX $%d, %s, $8, %s", 8*k, w, dst)
}

// op writes operation k of a batch, or the tail operation for k < 0, with label suffix s.
// It follows OPS_REST and FLAT_REST of decode-simd_arm64.s, with the literal length in LEN
// and the offset from the symbol, which is 0 for a repeat, so LAST keeps its value.
func (g *gen) op(lp loop, s string, k int) {
	g.byteOf("TW", k, "TOK")
	g.i("FLDPQ (LITP), (F0, F1)")
	switch {
	case lp.delta && lp.flat:
		g.i("SUB DST, DP, R16")
		g.i("CMP $32, LAST")
		g.i("CSEL HS, LAST, C32, R15")
		g.i("CMP R16, R15")
		g.i("CSEL HI, R16, R15, R15")
		g.i("SUB R15, DP, R14")
		g.i("FLDPQ (R14), (F2, F3)")
		g.i("VADD V2.B16, V0.B16, V0.B16")
		g.i("VADD V3.B16, V1.B16, V1.B16")
	case lp.delta:
		g.i("SUB DST, DP, R16")
		g.i("CMP R16, LAST")
		g.i("CSEL LO, LAST, R16, R15")
		g.i("SUB R15, DP, R14")
		g.i("FLDPQ (R14), (F2, F3)")
		g.i("CMP $32, R15")
		g.i("BLO dpattern%s", s)
		g.i("VADD V2.B16, V0.B16, V0.B16")
		g.i("VADD V3.B16, V1.B16, V1.B16")
		g.l("dstore" + s)
	}
	g.i("FSTPQ (F0, F1), (DP)")
	g.byteOf("LW", k, "LEN")
	g.i("CMP $33, LEN")
	g.i("BEQ litlong%s", s)
	g.l("litback" + s)
	g.i("ADD LEN, DP")
	g.i("ADD LEN, LITP")
	g.byteOf("SW", k, "R14")
	g.i("MOVD (OFFTAB)(R14<<3), R14")
	g.i("LSR $3, POS, R15")
	g.i("MOVD (RAW)(R15), R15")
	g.i("AND $7, POS, R16")
	g.i("LSR R16, R15, R15")
	g.i("ANDW R14, R15, R15")
	g.i("UBFX $32, R14, $8, R16")
	// Only symbol 0 decodes to offset 0.
	g.i("ADDS R14>>40, R15, R14")
	g.i("ADD R16, POS")
	g.i("CSEL NE, R14, LAST, LAST")
	if lp.flat {
		g.i("CMP TOK>>2, LAST")
		g.i("BLO raise%s", s)
		g.l("clampcheck" + s)
		g.i("SUBS LAST, DP, R14")
		g.i("CCMP HS, R14, DST, $0")
		g.i("BLO clamp%s", s)
		g.l("copy" + s)
		g.i("FLDPQ (R14), (F2, F3)")
		g.i("FSTPQ (F2, F3), (DP)")
	} else {
		g.i("SUBS LAST, DP, R14")
		g.i("CCMP HS, R14, DST, $0")
		g.i("BLO clamp%s", s)
		g.i("CMP TOK>>2, LAST")
		g.i("BLO pattern%s", s)
		g.i("FLDPQ (R14), (F2, F3)")
		g.i("FSTPQ (F2, F3), (DP)")
		g.l("check" + s)
	}
	g.i("CMP $132, TOK")
	g.i("BHS long%s", s)
	g.l("next" + s)
	g.i("ADD TOK>>2, DP")
}

// slow writes the out-of-line paths of the operation with label suffix s.
func (g *gen) slow(lp loop, s string) {
	if lp.delta && !lp.flat {
		g.l("dpattern" + s)
		g.i("ADD R15<<5, PERMTAB, R16")
		g.i("FLDPQ (R16), (F4, F5)")
		g.i("VTBL V4.B16, [V2.B16, V3.B16], V6.B16")
		g.i("VTBL V5.B16, [V2.B16, V3.B16], V7.B16")
		g.i("VADD V6.B16, V0.B16, V0.B16")
		g.i("VADD V7.B16, V1.B16, V1.B16")
		g.i("B dstore%s", s)
	}
	g.l("litlong" + s)
	g.i("MOVBU.P 1(ESCP), R15")
	g.i("ADD $33, R15, LEN")
	g.i("ADD $32, R15")
	g.i("LSR $5, R15")
	g.i("ADD $32, LITP, R14")
	g.i("ADD $32, DP, R16")
	g.l("litloop" + s)
	g.i("FLDPQ.P 32(R14), (F2, F3)")
	g.i("FSTPQ.P (F2, F3), 32(R16)")
	g.i("SUBS $1, R15")
	g.i("BNE litloop%s", s)
	g.i("B litback%s", s)
	if lp.flat {
		g.l("raise" + s)
		g.i("LSR $2, TOK, R16")
		g.i("CMP $33, R16")
		g.i("BNE raised%s", s)
		g.i("CMP $32, LAST")
		g.i("BHS clampcheck%s", s)
		g.i("MOVD $32, R16")
		g.l("raised" + s)
		g.i("SUB R16, DP, R14")
		g.i("B copy%s", s)
		g.l("clamp" + s)
		g.i("MOVD DST, R14")
		g.i("B copy%s", s)
	} else {
		g.l("pattern" + s)
		g.i("FLDPQ (R14), (F2, F3)")
		g.i("ADD LAST<<5, PERMTAB, R15")
		g.i("FLDPQ (R15), (F4, F5)")
		g.i("VTBL V4.B16, [V2.B16, V3.B16], V6.B16")
		g.i("VTBL V5.B16, [V2.B16, V3.B16], V7.B16")
		g.i("FSTPQ (F6, F7), (DP)")
		g.i("B check%s", s)
		g.l("clamp" + s)
		g.i("MOVD DST, R14")
		g.i("SUB DST, DP, R16")
		g.i("FLDPQ (R14), (F2, F3)")
		g.i("CMP TOK>>2, R16")
		g.i("BHS clampcopy%s", s)
		g.i("ADD R16<<5, PERMTAB, R15")
		g.i("FLDPQ (R15), (F4, F5)")
		g.i("VTBL V4.B16, [V2.B16, V3.B16], V2.B16")
		g.i("VTBL V5.B16, [V2.B16, V3.B16], V3.B16")
		g.l("clampcopy" + s)
		g.i("FSTPQ (F2, F3), (DP)")
		g.i("B check%s", s)
	}
	g.l("long" + s)
	if !lp.flat {
		g.i("SUB R14, DP, R16")
		g.i("CMP $32, R16")
		g.i("BHS longok%s", s)
		g.i("MOVD $1, R15")
		g.i("MOVD R15, 24(ST)")
		g.l("longok" + s)
	}
	g.i("MOVBU.P 1(ESCP), R15")
	g.i("ADD $33, R15, TOK")
	g.i("LSL $2, TOK")
	g.i("ADD $32, R15")
	g.i("LSR $5, R15")
	g.i("ADD $32, R14")
	g.i("ADD $32, DP, R16")
	g.l("longloop" + s)
	g.i("FLDPQ.P 32(R14), (F2, F3)")
	g.i("FSTPQ.P (F2, F3), 32(R16)")
	g.i("SUBS $1, R15")
	g.i("BNE longloop%s", s)
	g.i("B next%s", s)
}
