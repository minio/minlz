package kernel

import (
	"github.com/klauspost/cpuid/v2"
	"github.com/minio/minlz/internal/race"
)

// AVX2 tier entry points; the assembly is generated by _generate/pivco (enc_avx2.go,
// dec_avx2.go). The slicing below asserts the lengths the encoder kernels rely on:
// reads of src and ranks and stores to ranks[:n] and the packed region are exact;
// right-side and bitmap stores use RankSlack. The histogram is generic, as upstream's.

// The partitions store 16 bytes at right+nr and 2 bitmap bytes at the tail's offset.
const _ uint = RankSlack - 16

func hasAVX2() bool {
	return cpuid.CPU.Supports(cpuid.AVX2, cpuid.BMI2, cpuid.POPCNT)
}

func gatherAVX2(ranks, src []byte, s2r *[256]byte) uint8 {
	n := len(src)
	if n == 0 {
		return 0
	}
	ranks = ranks[:n]
	race.ReadSlice(src)
	race.ReadSlice(s2r[:])
	race.WriteSlice(ranks)
	return gatherAVX2Asm(&ranks[0], &src[0], n, s2r)
}

func partFullAVX2(ranks []byte, n int, right, bm []byte, thr uint8) int {
	if n == 0 {
		return 0
	}
	ranks, right, bm = ranks[:n], right[:n+RankSlack], bm[:(n+7)/8+RankSlack]
	race.WriteSlice(ranks)
	race.WriteSlice(right)
	race.WriteSlice(bm)
	return partFullAVX2Asm(&ranks[0], &right[0], &bm[0], n, thr)
}

func partRightAVX2(ranks []byte, n int, right, bm []byte, thr uint8) int {
	if n == 0 {
		return 0
	}
	ranks, right, bm = ranks[:n], right[:n+RankSlack], bm[:(n+7)/8+RankSlack]
	race.ReadSlice(ranks)
	race.WriteSlice(right)
	race.WriteSlice(bm)
	return partRightAVX2Asm(&ranks[0], &right[0], &bm[0], n, thr)
}

func partNoneAVX2(ranks []byte, n int, bm []byte, thr uint8) int {
	if n == 0 {
		return 0
	}
	ranks, bm = ranks[:n], bm[:(n+7)/8+RankSlack]
	race.ReadSlice(ranks)
	race.WriteSlice(bm)
	return partNoneAVX2Asm(&ranks[0], &bm[0], n, thr)
}

func packAVX2(dst, ranks []byte, n int, d, base uint8) {
	if n == 0 || d < 2 || d > 8 {
		packGeneric(dst, ranks, n, d, base)
		return
	}
	dst, ranks = dst[:(n*int(d)+7)/8], ranks[:n]
	n512, n128 := VertSplit(n, d)
	race.ReadSlice(ranks)
	race.WriteSlice(dst)
	packAVX2Asm(&dst[0], &ranks[0], n, n512, n128, d, base)
}

// execAVX2 runs the ops in one assembly call. Like execGeneric it checks each op before
// running it, so a malformed op fails closed.
func execAVX2(p *Program) int {
	if len(p.Ops) == 0 {
		return -1
	}
	if race.Enabled {
		race.ReadSlice(p.Ops)
		race.ReadSlice(p.In)
		if p.R2S != nil {
			race.ReadSlice(p.R2S[:])
		}
		race.WriteSlice(p.Arena)
		race.WriteSlice(p.Dst)
	}
	return execAVX2Asm(p)
}
