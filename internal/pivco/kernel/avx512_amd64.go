package kernel

import (
	"github.com/klauspost/cpuid/v2"
	"github.com/minio/minlz/internal/cpu"
	"github.com/minio/minlz/internal/race"
)

// AVX-512 tier entry points; the assembly is generated by _generate/pivco
// (enc_avx512.go, dec_avx512.go, hist_avx512.go). The slicing below asserts the lengths
// the assembly relies on: reads of src and ranks and stores to ranks[:n] and the packed
// region are exact; right-side and bitmap stores use RankSlack.

// The partitions store 64 bytes at right+nr, which can end 63 bytes past right[n], and 8
// bitmap bytes per 64 ranks (enc_avx512.go hardcodes both).
const _ uint = RankSlack - 63

// histChunk bounds one non-preemptible assembly call to about 70 µs. It is a whole number
// of the kernel's 65472-byte rounds, so the input alignment of every chunk is the same.
const histChunk = 16 * 65472

// hist_avx512.go rounds scratch up to 64 bytes and puts four 16 KiB bins there.
const _ uint = HistScratch - (4<<14 + 63)

// hasAVX512 is the feature set the AVX-512 kernels use; it matches upstream's
// requirement (pivco_huffman_primitives_avx512.h) plus BMI2/POPCNT for the scalar glue.
func hasAVX512() bool {
	return cpu.AVX512 && cpuid.CPU.Supports(cpuid.AVX512F, cpuid.AVX512BW, cpuid.AVX512VL, cpuid.AVX512VBMI,
		cpuid.AVX512VBMI2, cpuid.AVX512VPOPCNTDQ, cpuid.BMI2, cpuid.POPCNT)
}

// hasHistAVX512 gates the GFNI/BITALG histogram, which upstream builds only when both exist.
func hasHistAVX512() bool {
	return hasAVX512() && cpuid.CPU.Supports(cpuid.GFNI, cpuid.AVX512BITALG)
}

func gatherAVX512(ranks, src []byte, s2r *[256]byte) uint8 {
	n := len(src)
	if n == 0 {
		return 0
	}
	ranks = ranks[:n]
	race.ReadSlice(src)
	race.ReadSlice(s2r[:])
	race.WriteSlice(ranks)
	return gatherAsm(&ranks[0], &src[0], n, s2r)
}

func partFullAVX512(ranks []byte, n int, right, bm []byte, thr uint8) int {
	if n == 0 {
		return 0
	}
	ranks, right, bm = ranks[:n], right[:n+RankSlack], bm[:(n+7)/8+RankSlack]
	race.WriteSlice(ranks)
	race.WriteSlice(right)
	race.WriteSlice(bm)
	return partFullAsm(&ranks[0], &right[0], &bm[0], n, thr)
}

func partRightAVX512(ranks []byte, n int, right, bm []byte, thr uint8) int {
	if n == 0 {
		return 0
	}
	ranks, right, bm = ranks[:n], right[:n+RankSlack], bm[:(n+7)/8+RankSlack]
	race.ReadSlice(ranks)
	race.WriteSlice(right)
	race.WriteSlice(bm)
	return partRightAsm(&ranks[0], &right[0], &bm[0], n, thr)
}

func partNoneAVX512(ranks []byte, n int, bm []byte, thr uint8) int {
	if n == 0 {
		return 0
	}
	ranks, bm = ranks[:n], bm[:(n+7)/8+RankSlack]
	race.ReadSlice(ranks)
	race.WriteSlice(bm)
	return partNoneAsm(&ranks[0], &bm[0], n, thr)
}

func packAVX512(dst, ranks []byte, n int, d, base uint8) {
	if n == 0 || d < 2 || d > 8 {
		packGeneric(dst, ranks, n, d, base)
		return
	}
	dst, ranks = dst[:(n*int(d)+7)/8], ranks[:n]
	n512, n128 := VertSplit(n, d)
	race.ReadSlice(ranks)
	race.WriteSlice(dst)
	packAsm(&dst[0], &ranks[0], n, n512, n128, d, base)
}

// execAVX512 runs the ops in one assembly call. Like execGeneric it checks each op before
// running it, so a malformed op fails closed.
func execAVX512(p *Program) int {
	if len(p.Ops) == 0 {
		return -1
	}
	if race.Enabled {
		race.ReadSlice(p.Ops)
		race.ReadSlice(p.In)
		if p.R2S != nil {
			race.ReadSlice(p.R2S[:])
		}
		race.WriteSlice(p.Arena)
		race.WriteSlice(p.Dst)
	}
	return execAVX512Asm(p)
}

func histogramAVX512(h *[256]uint32, src, scratch []byte) {
	if !hasHistAVX512() {
		histogramGeneric(h, src)
		return
	}
	if len(src) == 0 {
		return
	}
	scratch = scratch[:HistScratch]
	race.WriteSlice(scratch)
	race.WriteSlice(h[:])
	for len(src) > 0 {
		c := src[:min(len(src), histChunk)]
		src = src[len(c):]
		race.ReadSlice(c)
		histAsm(h, &c[0], len(c), &scratch[0])
	}
}
